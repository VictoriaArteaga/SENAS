import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
  Unique,
} from 'typeorm';
import { NumericTransformer } from '../../common/numeric.transformer';
import { Level } from '../../levels/entities/level.entity';
import { Sign } from '../../signs/entities/sign.entity';
import { User } from '../../users/entities/user.entity';
import type { EvaluationResponseDto } from '../dto/evaluation-response.dto';

/** Immutable history: rows are only inserted, never updated. */
@Entity({ name: 'evaluations' })
@Unique('ux_evaluations_user_attempt', ['userId', 'attemptId'])
@Index('ix_evaluations_user_created', ['userId', 'createdAt'])
@Index('ix_evaluations_user_sign', ['userId', 'signId'])
@Check('chk_evaluations_precision_0_100', 'precision between 0 and 100')
@Check('chk_evaluations_stars', 'reported_stars between 0 and 3')
@Check('chk_evaluations_reported_xp', 'reported_xp >= 0')
@Check('chk_evaluations_awarded_xp', 'awarded_xp >= 0')
@Check('chk_evaluations_duration', 'duration_ms is null or duration_ms >= 0')
export class Evaluation {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ name: 'user_id', type: 'uuid' })
  userId: string;

  @ManyToOne(() => User, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'user_id' })
  user?: User;

  @Column({ name: 'sign_id', type: 'uuid' })
  signId: string;

  @ManyToOne(() => Sign, { nullable: false })
  @JoinColumn({ name: 'sign_id' })
  sign?: Sign;

  @Column({ name: 'level_id', type: 'uuid' })
  levelId: string;

  @ManyToOne(() => Level, { nullable: false })
  @JoinColumn({ name: 'level_id' })
  level?: Level;

  /** UUID generated by Unity; together with the user it makes submission idempotent. */
  @Column({ name: 'attempt_id', type: 'uuid' })
  attemptId: string;

  @Column({
    name: 'precision',
    type: 'numeric',
    precision: 5,
    scale: 2,
    transformer: NumericTransformer,
  })
  precision: number;

  @Column({ name: 'reported_stars', type: 'smallint' })
  reportedStars: number;

  @Column({ name: 'reported_xp', type: 'int' })
  reportedXp: number;

  @Column({ name: 'passed', type: 'boolean' })
  passed: boolean;

  @Column({ name: 'awarded_xp', type: 'int' })
  awardedXp: number;

  @Column({ name: 'duration_ms', type: 'int', nullable: true })
  durationMs: number | null;

  @Column({ name: 'feedback', type: 'varchar', length: 500, nullable: true })
  feedback: string | null;

  /** Response delivered the first time; resent as-is on identical retries. */
  @Column({ name: 'response', type: 'jsonb', nullable: true })
  response: EvaluationResponseDto | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;
}
